const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const data=require('./data.js');
const listeners={},dom={innerHTML:''},storage={};
const sandbox={console,Math,Date,Set,Array,String,Number,JSON,module:{exports:{}},location:{hash:''},confirm:()=>true,
 document:{querySelector:()=>dom,querySelectorAll:()=>[],addEventListener:(name,fn)=>{listeners[name]=fn;}},
 window:{scrollTo(){},addEventListener(){}},localStorage:{getItem:key=>storage[key]||null,setItem:(key,value)=>storage[key]=value}};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('data.js','utf8'),sandbox);
vm.runInContext(fs.readFileSync('app.js','utf8'),sandbox);
const {grade,matches,shuffle}=sandbox.module.exports;
assert.equal(data.REVIEW_TOPICS.length,12);
assert.equal(new Set(data.QUESTIONS.map(q=>q.id)).size,data.QUESTIONS.length);
for(const t of data.REVIEW_TOPICS){assert(data.IDENTIFICATION.some(q=>q.topic===t.id),t.title+' identification');assert(data.ENUMERATION.some(q=>q.topic===t.id),t.title+' enumeration');}
assert(matches('  TUMBLR.  ','Tumblr'));
assert(matches('Frozen','Static or Frozen',['Frozen','Static']));
assert(matches('Extemporaneuos','Extemporaneous'));
assert(!matches('Formal','Informal'));
assert(!matches('','Tumblr'));
assert(!matches('O','M'));
const semi=data.ENUMERATION.find(q=>q.topic==='semiotic');
assert.equal(grade(semi,['Visual','Spatial','Audio','Linguistic','Gestural']).points,5);
assert.equal(grade(semi,['Audio','Audio','Audio','Audio','Audio']).points,1);
assert.equal(grade(semi,['Visual','','Audio','','']).points,2);
const smart=data.ENUMERATION.find(q=>q.answers[0]==='Specific');
assert.equal(grade(smart,['Specific','Measurable','Achievable','Relevant','Time bound']).points,5);
assert.equal(grade(smart,['Measurable','Specific','Achievable','Relevant','Time bound']).points,3);
for(const q of data.QUESTIONS){const a=q.type==='identification'?[q.answer]:q.answers;assert.equal(grade(q,a).points,a.length,q.id+' exact answer');}
assert.equal(shuffle(data.QUESTIONS).length,data.QUESTIONS.length);
vm.runInContext("startFlash('register','identification')",sandbox);
const click=dataset=>listeners.click({target:{closest:s=>s==='button'?{dataset}:null},preventDefault(){}});
click({action:'reveal'});assert(dom.innerHTML.includes('THE ANSWER'));
click({action:'flash-mark',value:'got'});
assert.equal(vm.runInContext('flash.index',sandbox),1);
assert.equal(JSON.parse(storage['purcom-study-v1']).lastFlash.index,1);
assert.equal(JSON.parse(storage['purcom-study-v1']).lastFlash.deck.length,6);
click({nav:'home'});click({action:'continue'});
assert.equal(vm.runInContext('flash.index',sandbox),1,'continue preserves card position');
vm.runInContext("startFlash('visual','enumeration')",sandbox);
click({action:'reveal'});click({action:'flash-mark',value:'again'});
assert.equal(vm.runInContext('flash.done',sandbox),true);
click({action:'next-topic'});
assert.equal(vm.runInContext('flash.topic',sandbox),'business','topics follow notes order');
assert.equal(vm.runInContext('flash.type',sandbox),'enumeration','next topic keeps card type');
click({action:'reset'});
vm.runInContext("beginQuiz(IDENTIFICATION.slice(0,2),'practice')",sandbox);
vm.runInContext('submit([run.deck[0].answer])',sandbox);
assert.equal(vm.runInContext('run.index',sandbox),0,'practice waits for next');
click({action:'next-question'});
vm.runInContext('submit([run.deck[1].answer])',sandbox);
click({action:'next-question'});
assert.equal(JSON.parse(storage['purcom-study-v1']).history[0].percent,100);
vm.runInContext("beginQuiz(IDENTIFICATION.slice(0,2),'exam');submit(['wrong']);submit(['wrong'])",sandbox);
assert.equal(vm.runInContext('run.index',sandbox),2,'exam automatically advances');
assert.equal(JSON.parse(storage['purcom-study-v1']).history[0].percent,0);
assert.equal(JSON.parse(storage['purcom-study-v1']).missed.length,2);
click({action:'retry-run'});
assert.equal(vm.runInContext('run.deck.length',sandbox),2);
click({action:'reset'});
assert.equal(JSON.parse(storage['purcom-study-v1']).history.length,0);
console.log(`PASS: ${data.REVIEW_TOPICS.length} topics; ${data.IDENTIFICATION.length} identification cards; ${data.ENUMERATION.length} enumeration cards. Scoring, duplicates, order, practice/exam, retry, saved progress, and reset verified.`);
